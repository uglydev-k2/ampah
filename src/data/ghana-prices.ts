export function getGhanaPrice(name: string): number {
  if (GHANA_PRICES[name] !== undefined) return GHANA_PRICES[name];

  const lower = name.toLowerCase();
  if (/injection/.test(lower)) return 45;
  if (/gel|cream|rub|emulgel|patch|balm|freeze|heat|relief gel/.test(lower)) return 35;
  if (/syrup|suspension|drink|emulsion|tonic/.test(lower)) return 28;
  if (/suppositor/.test(lower)) return 18;
  if (/powder/.test(lower)) return 12;
  if (/capsule|softgel|oil|omega|vitamin|supplement|multivitamin/.test(lower)) return 55;
  if (/tablet|mg|caplet|codamol|acid/.test(lower)) return 15;

  return 20;
}

